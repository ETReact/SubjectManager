# Generates the plugin icons (Images\*.png) and PluginImages.cs with their base64 content.
# Usage: powershell -ExecutionPolicy Bypass -File tools\GenerateIcons.ps1
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$imgDir = Join-Path $root 'Images'
New-Item -ItemType Directory -Force $imgDir | Out-Null

function New-RoundedRect([float]$x, [float]$y, [float]$w, [float]$h, [float]$r) {
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    $d = $r * 2
    $p.AddArc($x, $y, $d, $d, 180, 90)
    $p.AddArc($x + $w - $d, $y, $d, $d, 270, 90)
    $p.AddArc($x + $w - $d, $y + $h - $d, $d, $d, 0, 90)
    $p.AddArc($x, $y + $h - $d, $d, $d, 90, 90)
    $p.CloseFigure()
    return $p
}

function New-Icon([int]$size) {
    # Drawn on a 256 canvas, then downscaled with high-quality resampling
    $S = 256
    $big = New-Object System.Drawing.Bitmap $S, $S
    $g = [System.Drawing.Graphics]::FromImage($big)
    $g.SmoothingMode = 'AntiAlias'
    $g.Clear([System.Drawing.Color]::Transparent)

    # Background: rounded square with a diagonal gradient
    $bg = New-RoundedRect 8 8 240 240 48
    $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush(
        (New-Object System.Drawing.PointF 0, 0), (New-Object System.Drawing.PointF $S, $S),
        [System.Drawing.Color]::FromArgb(255, 72, 61, 189), [System.Drawing.Color]::FromArgb(255, 0, 150, 160))
    $g.FillPath($brush, $bg)

    $white = [System.Drawing.Color]::White
    $pen = New-Object System.Drawing.Pen $white, 12
    $pen.StartCap = 'Round'; $pen.EndCap = 'Round'; $pen.LineJoin = 'Round'

    # Tree: one root node with three children
    $g.DrawLine($pen, 128, 92, 128, 128)    # root -> bus
    $g.DrawLine($pen, 64, 128, 192, 128)    # horizontal bus
    foreach ($x in 64, 128, 192) { $g.DrawLine($pen, $x, 128, $x, 156) }

    $fill = New-Object System.Drawing.SolidBrush $white
    $g.FillPath($fill, (New-RoundedRect 88 44 80 50 14))           # root
    foreach ($x in 64, 128, 192) {
        $g.FillPath($fill, (New-RoundedRect ($x - 30) 154 60 44 12)) # children
    }
    # Accent lines inside the nodes (titles)
    $accent = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 72, 61, 189))
    $g.FillPath($accent, (New-RoundedRect 106 63 44 12 6))
    $accent2 = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 0, 150, 160))
    foreach ($x in 64, 128, 192) { $g.FillPath($accent2, (New-RoundedRect ($x - 16) 170 32 11 5)) }
    $g.Dispose()

    $bmp = New-Object System.Drawing.Bitmap $size, $size
    $g2 = [System.Drawing.Graphics]::FromImage($bmp)
    $g2.InterpolationMode = 'HighQualityBicubic'
    $g2.PixelOffsetMode = 'HighQuality'
    $g2.SmoothingMode = 'AntiAlias'
    $g2.Clear([System.Drawing.Color]::Transparent)
    $g2.DrawImage($big, 0, 0, $size, $size)
    $g2.Dispose(); $big.Dispose()

    $file = Join-Path $imgDir "icon$size.png"
    $bmp.Save($file, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    return [Convert]::ToBase64String([IO.File]::ReadAllBytes($file))
}

$small = New-Icon 32
$large = New-Icon 80

$cs = @"
// <auto-generated> Generated by tools\GenerateIcons.ps1 - do not edit by hand. </auto-generated>
namespace SubjectManager
{
    internal static class PluginImages
    {
        /// <summary>32x32 PNG used in the XrmToolBox tool list.</summary>
        public const string Small = "$small";

        /// <summary>80x80 PNG used in the XrmToolBox tool list (large view).</summary>
        public const string Large = "$large";
    }
}
"@
[IO.File]::WriteAllText((Join-Path $root 'PluginImages.cs'), $cs, (New-Object System.Text.UTF8Encoding($false)))
"Icons generated: $imgDir (32: $($small.Length) chars, 80: $($large.Length) chars)"
